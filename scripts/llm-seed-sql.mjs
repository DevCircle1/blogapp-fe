/**
 * Writes supabase/llm_models.sql from src/data/llmModels.js: the tables, RLS
 * policies, a price-history trigger, and the seed rows. Run: node scripts/llm-seed-sql.mjs
 */
import { writeFile } from 'node:fs/promises';
import { LLM_MODELS, MODEL_NOTES } from '../src/data/llmModels.js';

const q = (value) => (value == null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const n = (value) => (value == null ? 'null' : String(value));

const rows = LLM_MODELS.map((model) => `  (${q(model.slug)}, ${q(model.provider)}, ${q(model.name)}, ${q(model.tokenizer)}, ${n(model.context)}, ${n(model.input)}, ${n(model.output)}, ${n(model.cached)}, true, ${q(MODEL_NOTES[model.slug] || model.promo || null)})`);

const sql = `-- LLM token counter / cost calculator data. Generated by scripts/llm-seed-sql.mjs.
-- Edit a row (price, is_active, notes) and the tool picks it up without a deploy.
create table if not exists llm_models (
  slug text primary key,
  provider text not null,
  display_name text not null,
  tokenizer text not null,
  context_window int,
  input_per_1m numeric not null,
  output_per_1m numeric not null,
  cached_input_per_1m numeric,
  is_active boolean default true,
  notes text,
  updated_at timestamptz default now()
);
alter table llm_models enable row level security;
drop policy if exists "public read" on llm_models;
create policy "public read" on llm_models for select to anon using (true);

create table if not exists llm_price_history (
  id bigserial primary key,
  slug text references llm_models(slug) on delete cascade,
  input_per_1m numeric,
  output_per_1m numeric,
  changed_at timestamptz default now()
);
alter table llm_price_history enable row level security;
drop policy if exists "public read" on llm_price_history;
create policy "public read" on llm_price_history for select to anon using (true);

-- Every insert or price change also lands in the history table, and bumps updated_at.
create or replace function llm_models_track() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' or new.input_per_1m is distinct from old.input_per_1m or new.output_per_1m is distinct from old.output_per_1m then
    insert into llm_price_history (slug, input_per_1m, output_per_1m) values (new.slug, new.input_per_1m, new.output_per_1m);
  end if;
  new.updated_at = now();
  return new;
end $$;
drop trigger if exists llm_models_track on llm_models;
create trigger llm_models_track before insert or update on llm_models for each row execute function llm_models_track();

insert into llm_models (slug, provider, display_name, tokenizer, context_window, input_per_1m, output_per_1m, cached_input_per_1m, is_active, notes) values
${rows.join(',\n')}
on conflict (slug) do update set
  provider = excluded.provider, display_name = excluded.display_name, tokenizer = excluded.tokenizer,
  context_window = excluded.context_window, input_per_1m = excluded.input_per_1m,
  output_per_1m = excluded.output_per_1m, cached_input_per_1m = excluded.cached_input_per_1m,
  notes = excluded.notes;
`;
await writeFile('supabase/llm_models.sql', sql, 'utf8');
console.log(`Wrote supabase/llm_models.sql with ${LLM_MODELS.length} models.`);
