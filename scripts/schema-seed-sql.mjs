/** Writes supabase/schema_type_status.sql from the bundled type definitions. Run: node scripts/schema-seed-sql.mjs */
import { writeFile } from 'node:fs/promises';
import { SCHEMA_TYPES } from '../src/lib/schema/registry.js';

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const rows = SCHEMA_TYPES.map((type) => `  (${q(type.slug)}, ${type.status.richResult === 'eligible'}, ${q(type.status.googleNotes)}, ${q(type.status.docsUrl)}, ${q(type.status.verifiedOn)})`);
const sql = `-- Rich-result eligibility per schema type. Generated by scripts/schema-seed-sql.mjs.
-- When Google changes what it supports, update the row (and verified_on) here and
-- the warning on the generator page changes without a deploy.
create table if not exists schema_type_status (
  slug text primary key,
  rich_result_eligible boolean not null,
  google_notes text,
  docs_url text,
  verified_on date not null
);
alter table schema_type_status enable row level security;
drop policy if exists "public read" on schema_type_status;
create policy "public read" on schema_type_status for select to anon using (true);

insert into schema_type_status (slug, rich_result_eligible, google_notes, docs_url, verified_on) values
${rows.join(',\n')}
on conflict (slug) do update set
  rich_result_eligible = excluded.rich_result_eligible, google_notes = excluded.google_notes,
  docs_url = excluded.docs_url, verified_on = excluded.verified_on;
`;
await writeFile('supabase/schema_type_status.sql', sql, 'utf8');
console.log(`Wrote supabase/schema_type_status.sql with ${SCHEMA_TYPES.length} types.`);
