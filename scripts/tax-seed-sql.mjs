/** Writes supabase/tax_years.sql from src/data/pkTaxYears.js. Run: node scripts/tax-seed-sql.mjs */
import { writeFile } from 'node:fs/promises';
import { TAX_YEARS } from '../src/data/pkTaxYears.js';

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const rows = TAX_YEARS.map((year) => `  (${q(year.id)}, ${q(year.country)}, ${q(year.label)}, ${q(year.effectiveFrom)}, ${q(year.effectiveTo)}, ${year.isCurrent}, ${q(year.sourceUrl)}, ${q(year.verifiedOn)},
    ${q(JSON.stringify(year.slabs))}::jsonb,
    ${q(JSON.stringify({ surcharge: year.rules.surcharge, notes: year.rules.notes, sourceName: year.sourceName, taxYearName: year.taxYearName }))}::jsonb)`);

const sql = `-- Salaried-individual income tax by tax year. Generated by scripts/tax-seed-sql.mjs.
-- Update a slab or flip is_current in the Supabase dashboard and the calculator
-- picks it up without a deploy. Always keep source_url and verified_on truthful:
-- they are shown publicly on the page.
create table if not exists tax_years (
  id text primary key,
  country text not null,
  label text not null,
  effective_from date,
  effective_to date,
  is_current boolean default false,
  source_url text not null,
  verified_on date not null,
  slabs jsonb not null,      -- [{min, max, rate, fixed}]  tax = fixed + rate * (income - min)
  rules jsonb not null       -- {surcharge: {rate, threshold} | null, notes, sourceName, taxYearName}
);
alter table tax_years enable row level security;
drop policy if exists "public read" on tax_years;
create policy "public read" on tax_years for select to anon using (true);

insert into tax_years (id, country, label, effective_from, effective_to, is_current, source_url, verified_on, slabs, rules) values
${rows.join(',\n')}
on conflict (id) do update set
  label = excluded.label, effective_from = excluded.effective_from, effective_to = excluded.effective_to,
  is_current = excluded.is_current, source_url = excluded.source_url, verified_on = excluded.verified_on,
  slabs = excluded.slabs, rules = excluded.rules;
`;
await writeFile('supabase/tax_years.sql', sql, 'utf8');
console.log(`Wrote supabase/tax_years.sql with ${TAX_YEARS.length} tax years.`);
